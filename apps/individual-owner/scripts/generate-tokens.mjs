import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const owner = fileURLToPath(new URL('../', import.meta.url));
const tokens = JSON.parse(readFileSync(path.join(owner, 'design/tokens/tokens.json'), 'utf8'));
const check = process.argv.includes('--check');
function emit(name, value) {
  const target = path.join(owner, name);
  if (check) {
    if (readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== value) throw new Error(`Generated file drift: ${name}`);
  } else { mkdirSync(path.dirname(target), { recursive: true }); writeFileSync(target, value); }
}
const vars = (values) => Object.entries(values).map(([key, value]) => `  --${key.replace(/[A-Z]/g, c => `-${c.toLowerCase()}`)}: ${value};`).join('\n');
emit('web/src/design/tokens.css', `/* Generated by scripts/generate-tokens.mjs. */\n:root {\n${vars(tokens.light)}\n${Object.entries(tokens.radius).map(([k,v])=>`  --radius-${k}: ${v}px;`).join('\n')}\n  --font-ui: ${tokens.fontFamily};\n}\n[data-theme="dark"] {\n${vars(tokens.dark)}\n}\n`);
const dartColor = hex => `Color(0xFF${hex.slice(1)})`;
emit('mobile/lib/core/theme/design_tokens.dart', `// Generated by scripts/generate-tokens.mjs.\nimport 'package:flutter/material.dart';\n\nabstract final class DesignTokens {\n${['light', 'dark'].map(mode=>Object.entries(tokens[mode]).map(([k,v])=>`  static const ${mode}${k[0].toUpperCase()+k.slice(1)} = ${dartColor(v)};`).join('\n')).join('\n')}\n${Object.entries(tokens.radius).map(([k,v])=>`  static const ${k}Radius = ${v}.0;`).join('\n')}\n}\n`);
for (const name of ['dashboard', 'modules']) emit(`mobile/assets/${name}.json`, readFileSync(path.join(owner, `shared/${name}.json`), 'utf8'));
for (const target of ['mobile/assets/fonts','web/public/fonts']) {
  for (const name of ['Inter.ttf','OFL.txt']) {
    const source = readFileSync(path.join(owner,'shared/fonts',name));
    const destination = path.join(owner,target,name);
    if (check) assert.ok(source.equals(readFileSync(destination)), `Font drift: ${destination}`);
    else { mkdirSync(path.dirname(destination),{recursive:true}); writeFileSync(destination,source); }
  }
}
console.log(check ? 'Token and fixture parity verified.' : 'Generated CSS, Dart and mobile fixtures.');
