package e2e

import (
	"bytes"
	"io"
	"net/http"
	"strings"
	"testing"
	"time"

	"github.com/CosmicforgeHealthnet/cosmicforge-realestate/shared/go/ids"
	"github.com/CosmicforgeHealthnet/cosmicforge-realestate/shared/go/platform"
	testkit "github.com/CosmicforgeHealthnet/cosmicforge-realestate/shared/go/testing"
)

// TestOwnerFunctionalJourneyWithRealServices drives the owner's core journey
// through the gateway against the real verification-service,
// media-document-service, notification-service and JetStream, with the
// owner worker running its jobs: identity and property-authority
// verification, photos, listing publication and withdrawal (with
// marketplace read access to listing media following listing state), and a
// PDF report generated by the worker and stored in media-document-service.
func TestOwnerFunctionalJourneyWithRealServices(t *testing.T) {
	p := startOwnerPlatform(t, true)
	tok, ownerID := p.activeOwner(t)
	pdf := func(s string) []byte { return append([]byte("%PDF-1.7\n"), bytes.Repeat([]byte(s), 200)...) }

	// Identity verification (required to publish).
	idDoc := p.upload(t, tok, "VERIFICATION_DOCUMENT", "application/pdf", "NATIONAL_ID", pdf("identity "))
	if r := p.asUser(tok, "POST", "/api/v1/owner/verification", map[string]any{"evidence": []map[string]any{{"media_id": idDoc, "evidence_type": "ID_DOCUMENT_FRONT"}}},
		ids.New().String()); r.status != 201 {
		t.Fatalf("identity verification: %d %s", r.status, r.body)
	}
	testkit.Eventually(t, 45*time.Second, func() bool {
		r := p.asUser(tok, "GET", "/api/v1/owner/verification", nil, "")
		return r.status == 200 && strings.Contains(string(r.body), `"status":"VERIFIED"`)
	}, "identity never verified")

	// Property, ownership claim with a real deed, PROPERTY_AUTHORITY verification.
	r := p.asUser(tok, "POST", "/api/v1/owner/properties", map[string]any{"category": "RESIDENTIAL", "property_type": "APARTMENT", "title": "Journey home",
		"address": map[string]any{"line1": "3 E2E Road", "city": "Lagos", "state_region": "Lagos", "country_code": "NG", "latitude": 6.45, "longitude": 3.39}},
		ids.New().String())
	if r.status != 201 {
		t.Fatalf("property: %d %s", r.status, r.body)
	}
	var prop struct {
		ID ids.ID `json:"id"`
	}
	r.data(t, &prop)
	pp := "/api/v1/owner/properties/" + prop.ID.String()
	deed := p.upload(t, tok, "DOCUMENT", "application/pdf", "DEED_OF_ASSIGNMENT", pdf("deed "))
	if r := p.asUser(tok, "POST", pp+"/ownership", map[string]any{"documents": []map[string]any{{"media_id": deed, "document_type": "DEED_OF_ASSIGNMENT"}}},
		ids.New().String()); r.status != 200 {
		t.Fatalf("ownership claim: %d %s", r.status, r.body)
	}
	if r := p.asUser(tok, "POST", pp+"/verification", nil, ids.New().String()); r.status != 200 {
		t.Fatalf("property verification: %d %s", r.status, r.body)
	}
	testkit.Eventually(t, 45*time.Second, func() bool {
		var ov struct {
			Primary struct {
				Status string `json:"status"`
			} `json:"primary"`
		}
		r := p.asUser(tok, "GET", pp+"/ownership", nil, "")
		if r.status != 200 {
			return false
		}
		r.data(t, &ov)
		return ov.Primary.Status == "VERIFIED"
	}, "ownership authority never verified through verification-service")

	// Photos and a complete listing.
	jpeg := func(i int) []byte {
		return append([]byte{0xFF, 0xD8, 0xFF, 0xE0, byte(i)}, bytes.Repeat([]byte("photo"), 400)...)
	}
	var photos []ids.ID
	var selection []map[string]any
	for i := 0; i < 3; i++ {
		m := p.upload(t, tok, "IMAGE", "image/jpeg", "", jpeg(i))
		if r := p.asUser(tok, "POST", pp+"/media", map[string]any{"media_id": m, "purpose": "PHOTO", "position": i}, ids.New().String()); r.status != 201 {
			t.Fatalf("link photo: %d %s", r.status, r.body)
		}
		photos = append(photos, m)
		selection = append(selection, map[string]any{"media_id": m, "position": i, "is_cover": i == 0})
	}
	r = p.asUser(tok, "POST", "/api/v1/owner/listings", map[string]any{"property_id": prop.ID, "transaction_type": "RENT_LONG_TERM", "title": "Bright 3-bed flat",
		"description": strings.Repeat("Spacious and bright. ", 12), "details": map[string]any{"furnishing": "SEMI_FURNISHED", "min_term_months": 12},
		"media": selection}, ids.New().String())
	if r.status != 201 {
		t.Fatalf("listing: %d %s", r.status, r.body)
	}
	var l struct {
		ID ids.ID `json:"id"`
	}
	r.data(t, &l)
	lp := "/api/v1/owner/listings/" + l.ID.String()
	if r := p.ifMatch(tok, "PUT", lp+"/pricing", 0, map[string]any{"currency": "NGN", "base_amount_minor": 360000000, "base_period": "YEAR",
		"payment_cycle": "ANNUAL", "deposit_amount_minor": 50000000}); r.status != 200 {
		t.Fatalf("pricing: %d %s", r.status, r.body)
	}
	marketplaceCanRead := func(id ids.ID) bool {
		return p.asService(platform.MarketplaceService, platform.MediaDocumentService, "POST", "/internal/v1/media/"+id.String()+"/download-url",
			map[string]any{"purpose": "listing_display"}, "").status == 200
	}
	if marketplaceCanRead(photos[0]) {
		t.Fatal("marketplace can read a draft listing's photo")
	}
	if r := p.asUser(tok, "POST", lp+"/publish", nil, ids.New().String()); r.status != 200 || !strings.Contains(string(r.body), `"status":"PUBLISHED"`) {
		t.Fatalf("publish: %d %s", r.status, r.body)
	}
	testkit.Eventually(t, 30*time.Second, func() bool {
		for _, m := range photos {
			if !marketplaceCanRead(m) {
				return false
			}
		}
		return true
	}, "marketplace never got read access to the published listing's photos")
	// Extend the existing real-service harness rather than creating a second
	// platform suite. Future source actors remain explicitly signed simulators.
	p.certifyPrimaryOwnerJourneys(tok, ownerID, prop.ID, l.ID, photos[0], deed)
	if r := p.asUser(tok, "POST", lp+"/withdraw", nil, ids.New().String()); r.status != 200 || !strings.Contains(string(r.body), `"status":"WITHDRAWN"`) {
		t.Fatalf("withdraw: %d %s", r.status, r.body)
	}
	testkit.Eventually(t, 30*time.Second, func() bool { return !marketplaceCanRead(photos[0]) },
		"marketplace kept read access after the listing was withdrawn")

	// A PDF report generated by the worker and stored in media-document-service.
	today := time.Now().UTC().Format(time.DateOnly)
	r = p.asUser(tok, "POST", "/api/v1/owner/reports/export", map[string]any{"report_type": "PORTFOLIO", "from": today, "to": today}, ids.New().String())
	if r.status != 202 {
		t.Fatalf("report export: %d %s", r.status, r.body)
	}
	var rep struct {
		ID          ids.ID  `json:"id"`
		Status      string  `json:"status"`
		DownloadURL *string `json:"download_url"`
	}
	r.data(t, &rep)
	testkit.Eventually(t, 45*time.Second, func() bool {
		r := p.asUser(tok, "GET", "/api/v1/owner/reports/"+rep.ID.String(), nil, "")
		if r.status != 200 {
			return false
		}
		r.data(t, &rep)
		return rep.Status == "READY" && rep.DownloadURL != nil
	}, "report never became READY")
	resp, err := http.Get(*rep.DownloadURL)
	if err != nil {
		t.Fatal(err)
	}
	body, _ := io.ReadAll(resp.Body)
	resp.Body.Close()
	if resp.StatusCode != 200 || !bytes.HasPrefix(body, []byte("%PDF")) {
		t.Fatalf("report download: %d %q", resp.StatusCode, body[:min(len(body), 40)])
	}
}
